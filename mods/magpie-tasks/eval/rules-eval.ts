// Jev's routing-rule judgment against the person's labels (plan section 12.3, unverified behaviour U7),
// and the upkeep of the test data modules. Run with bun from the plugin folder:
//
//   bun eval/rules-eval.ts extract [--limit 200] [--include-tmp] [--out DIR]
//       the latest delegation briefs (first user text of ~/.claude/projects/**/subagents/agent-*.jsonl,
//       control lines removed by briefForJev) → DIR/briefs.jsonl
//   bun eval/rules-eval.ts sheet [--out DIR] [--key FILE] [--model gpt-6-luna]
//       one Jev request per brief (rule choice + deep) → DIR/sheet.jsonl, a labelling sheet: fill
//       each row's label.rule (a rule id or none) and label.deep (true or false)
//   bun eval/rules-eval.ts score [--out DIR]
//       rule accuracy, none recall, coverage and accuracy at each rule threshold, deep AUC and
//       accuracy at each deep threshold, suggested thresholds → stdout and DIR/score.md
//   bun eval/rules-eval.ts data [--dumps /tmp/magpie-probe-recheck-JQE9/out]
//       copies the six probe dumps to tests/data/api-*.json (with --dumps), then regenerates the
//       modules tests/*.test.ts import (claude plugin test loads code files only, never JSON):
//       tests/data/api-dumps.ts, tests/data/jev-responses.ts, tests/data/jev-rules.ts
//
// DIR defaults to ~/.config/magpie-tasks/eval. The key is read from its file and never printed.
