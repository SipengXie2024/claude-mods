import { ask, type JevConfig } from '../src/jev'
import { decideRule, spawnJudgment, spawnQuestions } from '../src/judge'
import { loadRules, type Rules } from '../src/rules'
import type { JevJudgment } from '../src/types'
import { nodeIo } from '../io-tests/node-io'

export const PLUGIN_ROOT = join(import.meta.dir, '..')
const DATA = join(PLUGIN_ROOT, 'tests/data')

