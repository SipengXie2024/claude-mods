const camel = (s: string) => s.replace(/[-.]+([a-z0-9])/g, (_, c: string) => c.toUpperCase())

// The generated modules, path → text: verbatim JSON from tests/data and rules/ as TypeScript values.
export function dataModules(): Record<string, string> {
  const head = (from: string) => `// Generated by \`bun eval/rules-eval.ts data\` from ${from}; do not edit.\n// claude plugin test loads code files only, so the JSON files are carried here verbatim.\n`
  const dumps = [
    head('tests/data/api-*.json (copies of /tmp/magpie-probe-recheck-JQE9/out dumps, Claude Code 2.1.319, through redactDump)'),
    'export type Dump = { api: Array<{ role: string; content: unknown }>; event?: { answer?: string; agentId?: string; [k: string]: unknown }; [k: string]: unknown }\n',
    ...Object.entries(DUMPS).map(([name, file]) => `\nexport const ${name}: Dump = ${readFileSync(join(DATA, `api-${file}.json`), 'utf8').trim()}\n`),
  ].join('')
  const saved = readdirSync(DATA).filter(f => /^jev-.*\.json$/.test(f)).sort()
  const responses = [
    head('tests/data/jev-*.json (real Decisions responses saved by io-tests with SAVE_JEV_DATA=1, and a real evaluator reply)'),
    'export type SavedDecision = { kind: \'decisions\'; at: string; request: { model: string; input: Array<{ role: \'user\' | \'assistant\'; content: string }>; questions: Array<{ name: string; type: \'choice\'; instructions: string; choices: { value: string; description: string }[] } | { name: string; type: \'predicate\'; instructions: string }> }; status: number; body: string }\n',
    'export type SavedSubstitute = { kind: \'substitute\'; at: string; model: string; command: string; prompt: string; reply: string }\n',
    ...saved.map(f => {
      const json = readFileSync(join(DATA, f), 'utf8').trim()
      const kind = (JSON.parse(json) as { kind: string }).kind
      return `\nexport const ${camel(f.replace(/\.json$/, ''))}: ${kind === 'substitute' ? 'SavedSubstitute' : 'SavedDecision'} = ${json}\n`
    }),
  ].join('')
  const rules = `${head('rules/routing-rules.json')}\nexport const routingRules: unknown = ${readFileSync(join(PLUGIN_ROOT, 'rules/routing-rules.json'), 'utf8').trim()}\n`
  return {
    [join(DATA, 'api-dumps.ts')]: dumps,
    [join(DATA, 'jev-responses.ts')]: responses,
    [join(DATA, 'jev-rules.ts')]: rules,
  }
}

// The reminders of a captured request that carry the person's instruction files and personal context
// (CLAUDE.md, AGENTS.md, the memory index, the email), replaced by a one-line placeholder so the dumps
// can sit in a public repository; the text is the dump's JSON, so a newline is the two characters \n.
const PRIVATE_REMINDERS: [RegExp, string][] = [
  [/<system-reminder>\\nCodebase and user instructions are shown below\..*?<\/system-reminder>/g, "<system-reminder>\\nCodebase and user instructions are shown below. [The person's instruction files (CLAUDE.md, AGENTS.md and the memory index) are removed from this fixture.]\\n</system-reminder>"],
  [/<system-reminder>\\nAs you answer the user's questions, you can use the following context:.*?<\/system-reminder>/g, "<system-reminder>\\nAs you answer the user's questions, you can use the following context: [the person's context is removed from this fixture.]\\n</system-reminder>"],
]

export function redactDump(json: string): string {
  return PRIVATE_REMINDERS.reduce((text, [pattern, placeholder]) => text.replace(pattern, () => placeholder), json)
}

function data(args: Map<string, string>): void {
  const from = args.get('dumps')
  if (from !== undefined) {
    for (const file of Object.values(DUMPS)) writeFileSync(join(DATA, `api-${file}.json`), redactDump(readFileSync(join(from, `${file}.json`), 'utf8')))
    console.log(`copied ${Object.keys(DUMPS).length} dumps from ${from}`)
  }
  for (const [path, text] of Object.entries(dataModules())) {
    writeFileSync(path, text)
    console.log(`wrote ${path} (${text.length} chars)`)
  }
}

// ---- extract ----------------------------------------------------------------------------------

interface BriefRow { id: string; source: string; at: string; agentType: string | null; description: string | null; chars: number; brief: string }

function firstUserText(path: string): { text: string; at: string } | null {
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (line.trim() === '') continue
    const row = JSON.parse(line) as { type?: string; timestamp?: string; message?: { role?: string; content?: unknown } }
    if (row.type !== 'user' || row.message?.role !== 'user') continue
    const c = row.message.content
    const text = typeof c === 'string' ? c
      : Array.isArray(c) ? (c as { type?: string; text?: unknown }[]).filter(b => b.type === 'text' && typeof b.text === 'string' && !/^<system-reminder(\s[^>]*)?>/.test(b.text as string)).map(b => b.text as string).join('\n')
        : ''
    return text.trim() === '' ? null : { text, at: row.timestamp ?? '' }
  }
  return null
}

function transcripts(includeTmp: boolean): string[] {
  const root = join(homedir(), '.claude/projects')
  const out: string[] = []
  for (const project of readdirSync(root)) {
    if (!includeTmp && project.startsWith('-tmp')) continue
    const pdir = join(root, project)
    if (!statSync(pdir).isDirectory()) continue
    for (const session of readdirSync(pdir)) {
      const sdir = join(pdir, session, 'subagents')
      if (!existsSync(sdir)) continue
      // Forks carry their parent's context rather than a brief of their own.
      for (const f of readdirSync(sdir)) if (/^agent-.*\.jsonl$/.test(f) && !f.startsWith('agent-afork-')) out.push(join(sdir, f))
    }
  }
  return out.sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)
}

function extract(args: Map<string, string>, dir: string): void {
  const limit = Number(args.get('limit') ?? '200')
  const seen = new Set<string>()
  const rows: BriefRow[] = []
  for (const path of transcripts(args.has('include-tmp'))) {
    if (rows.length >= limit) break
    const first = firstUserText(path)
    if (first === null) continue
    const brief = briefForJev(first.text)
    if (brief === '' || seen.has(brief)) continue
    seen.add(brief)
    const metaPath = path.replace(/\.jsonl$/, '.meta.json')
    const meta = existsSync(metaPath) ? JSON.parse(readFileSync(metaPath, 'utf8')) as { agentType?: string; description?: string } : {}
    rows.push({ id: basename(path, '.jsonl'), source: path, at: first.at, agentType: meta.agentType ?? null, description: meta.description ?? null, chars: brief.length, brief })
  }
  mkdirSync(dir, { recursive: true })
  writeFileSync(join(dir, 'briefs.jsonl'), rows.map(r => JSON.stringify(r)).join('\n') + '\n')
  console.log(`wrote ${rows.length} briefs to ${join(dir, 'briefs.jsonl')}`)
}

// ---- sheet ------------------------------------------------------------------------------------

interface SheetRow extends BriefRow {
  rulesVersion: string
  jev: { ok: true; judgment: JevJudgment } | { ok: false; error: string }
  label: { rule: string | null; deep: boolean | null; note: string }
}

const readJsonl = <T>(path: string): T[] => readFileSync(path, 'utf8').split('\n').filter(l => l.trim() !== '').map(l => JSON.parse(l) as T)

async function sheet(args: Map<string, string>, dir: string, rules: Rules): Promise<void> {
  const cfg: JevConfig = {
    url: 'https://api.openai.com/v1/decisions',
    model: args.get('model') ?? 'gpt-6-luna',
    keyFile: args.get('key') ?? join(homedir(), '.config/jev-opus/openai-jev.key'),
    deadlineMs: 30000,
  }
  const briefs = readJsonl<BriefRow>(join(dir, 'briefs.jsonl'))
  const path = join(dir, 'sheet.jsonl')
  // Rows already judged (and possibly labelled) are kept as they are; only new briefs are asked.
  const done = existsSync(path) ? readJsonl<SheetRow>(path) : []
  const have = new Set(done.filter(r => r.jev.ok).map(r => r.id))
  const rows = done.filter(r => r.jev.ok)
  const io = nodeIo()
  const questions = spawnQuestions(rules)
  let failed = 0
  for (const b of briefs) {
    if (have.has(b.id)) continue
    // The brief alone, in the format of a delegation (delegationMessages applies briefForJev again:
    // briefs.jsonl may predate the current cut). Live routing also gives Jev the spawning conversation
    // and the files the brief names; briefs.jsonl holds neither.
    const r = await ask(io, cfg, delegationMessages([], [], b.brief), questions)
    const jev: SheetRow['jev'] = r.ok
      ? { ok: true, judgment: spawnJudgment(r.answers, { latencyMs: r.latencyMs, inputTokens: r.inputTokens, ...(r.cachedTokens !== undefined ? { cachedTokens: r.cachedTokens } : {}) }, rules) }
      : { ok: false, error: r.error }
    if (!r.ok) failed++
    rows.push({ ...b, rulesVersion: rules.version, jev, label: { rule: null, deep: null, note: '' } })
    writeFileSync(path, rows.map(x => JSON.stringify(x)).join('\n') + '\n')
    console.log(`${b.id}: ${jev.ok ? `${jev.judgment.ruleChoice} ${jev.judgment.confidence.toFixed(2)}` : `failed: ${jev.error}`}`)
  }
  console.log(`sheet ${path}: ${rows.length} rows, ${failed} Jev failures this run`)
}

// ---- score ------------------------------------------------------------------------------------

const pct = (a: number, b: number) => (b === 0 ? '—' : `${((100 * a) / b).toFixed(0)}%`)

function auc(pos: number[], neg: number[]): number | null {
  if (pos.length === 0 || neg.length === 0) return null
  let s = 0
  for (const p of pos) for (const n of neg) s += p > n ? 1 : p === n ? 0.5 : 0
  return s / (pos.length * neg.length)
}

export function score(rows: SheetRow[], rules: Rules): string {
  const labelled = rows.filter(r => r.jev.ok && r.label.rule !== null) as (SheetRow & { jev: { ok: true; judgment: JevJudgment } })[]
  const out: string[] = [`# Jev rule judgment against labels (${rules.version}, ${labelled.length} labelled rows)`, '']
  if (labelled.length === 0) return out.concat('No labelled rows: fill label.rule (and label.deep) in sheet.jsonl first.').join('\n')
  const top = labelled.filter(r => r.jev.judgment.ruleChoice === r.label.rule).length
  const noneRows = labelled.filter(r => r.label.rule === 'none')
  const noneHit = noneRows.filter(r => 'none' in decideRule(r.jev.judgment, rules)).length
  out.push(`- Jev's first choice equals the label: ${top} of ${labelled.length} (${pct(top, labelled.length)})`)
  out.push(`- none recall at the current ruleConfidence ${rules.thresholds.ruleConfidence}: ${noneHit} of ${noneRows.length} (${pct(noneHit, noneRows.length)})`, '')
  out.push('| ruleConfidence | routed (coverage) | correct among routed | wrong routes | labelled none but routed | correct − wrong |', '| --- | --- | --- | --- | --- | --- |')
  let best = { t: 0, net: -Infinity }
  for (let i = 0; i <= 19; i++) {
    const t = Math.round(i * 5) / 100
    const routed = labelled.filter(r => r.jev.judgment.ruleChoice !== 'none' && r.jev.judgment.confidence >= t)
    const right = routed.filter(r => r.jev.judgment.ruleChoice === r.label.rule).length
    const wrong = routed.length - right
    const noneRouted = routed.filter(r => r.label.rule === 'none').length
    if (right - wrong > best.net) best = { t, net: right - wrong }
    out.push(`| ${t.toFixed(2)} | ${routed.length} (${pct(routed.length, labelled.length)}) | ${right} (${pct(right, routed.length)}) | ${wrong} | ${noneRouted} | ${right - wrong} |`)
  }
  out.push('', `Suggested ruleConfidence: ${best.t.toFixed(2)} (the lowest threshold with the most correct minus wrong routes; current ${rules.thresholds.ruleConfidence}).`, '')
  const deepRows = labelled.filter(r => r.label.deep !== null && r.jev.judgment.deepP !== null)
  const pos = deepRows.filter(r => r.label.deep === true).map(r => r.jev.judgment.deepP!)
  const neg = deepRows.filter(r => r.label.deep === false).map(r => r.jev.judgment.deepP!)
  const a = auc(pos, neg)
  out.push(`## Deep (${deepRows.length} rows labelled, ${pos.length} deep)`, '', `- AUC: ${a === null ? '—' : a.toFixed(3)}`, '')
  out.push('| deepYes | called deep | precision | recall | accuracy |', '| --- | --- | --- | --- | --- |')
  let bestDeep = { t: rules.thresholds.deepYes, acc: -1 }
  for (let i = 0; i <= 10; i++) {
    const t = Math.round(50 + i * 5) / 100
    const called = deepRows.filter(r => r.jev.judgment.deepP! >= t)
    const tp = called.filter(r => r.label.deep === true).length
    const correct = deepRows.filter(r => (r.jev.judgment.deepP! >= t) === r.label.deep).length
    if (correct > bestDeep.acc) bestDeep = { t, acc: correct }
    out.push(`| ${t.toFixed(2)} | ${called.length} | ${pct(tp, called.length)} | ${pct(tp, pos.length)} | ${pct(correct, deepRows.length)} |`)
  }
  if (deepRows.length > 0) out.push('', `Suggested deepYes: ${bestDeep.t.toFixed(2)} (the lowest threshold with the most correct calls; current ${rules.thresholds.deepYes}).`)
  out.push('', 'Thresholds chosen and scored on the same rows are optimistic; the person confirms them before the rules version is raised.')
  return out.join('\n')
}

// ---- main -------------------------------------------------------------------------------------

function parseArgs(argv: string[]): Map<string, string> {
  const m = new Map<string, string>()
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]!
    if (!a.startsWith('--')) throw new Error(`unexpected argument ${a}`)
    const next = argv[i + 1]
    if (next !== undefined && !next.startsWith('--')) { m.set(a.slice(2), next); i++ } else m.set(a.slice(2), '')
  }
  return m
}

if (import.meta.main) {
  const [cmd, ...rest] = process.argv.slice(2)
  const args = parseArgs(rest)
  const dir = args.get('out') ?? join(homedir(), '.config/magpie-tasks/eval')
  if (cmd === 'data') data(args)
  else if (cmd === 'extract') extract(args, dir)
  else if (cmd === 'sheet') await sheet(args, dir, await loadRules(nodeIo(), PLUGIN_ROOT))
  else if (cmd === 'score') {
    const text = score(readJsonl<SheetRow>(join(dir, 'sheet.jsonl')), await loadRules(nodeIo(), PLUGIN_ROOT))
    mkdirSync(dirname(join(dir, 'score.md')), { recursive: true })
    writeFileSync(join(dir, 'score.md'), text + '\n')
    console.log(text)
  } else {
    console.error('usage: bun eval/rules-eval.ts extract|sheet|score|data [options]; see the header of this file')
    process.exit(2)
  }
}
